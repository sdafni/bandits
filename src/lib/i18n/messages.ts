function readPath(tree: MessageTree, path: string): string | null {
  const parts = path.split(".");
  let current: string | MessageTree | undefined = tree;
  for (const part of parts) {
    if (!current || typeof current === "string") {
      return null;
    }
    current = current[part];
  }
  return typeof current === "string" ? current : null;
}

export function translate(locale: AppLocale, key: string) {
  const primary = readPath(messages[locale], key);
  if (primary) {
    return primary;
  }

  const fallbackLocale: AppLocale = locale === "el" ? "en" : "el";
  const fallback = readPath(messages[fallbackLocale], key);
  if (fallback) {
    return fallback;
  }

  return key;
}
